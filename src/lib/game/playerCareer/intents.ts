const HOLD: AlternativeIntent = { intent: 'hold' };

/** O lado que a situação exige e a intenção de cada alternativa; situação fora da tabela vale para os dois lados e não força nada. */
export function situationIntents(id: string): { side: SituationSide; alternatives: [AlternativeIntent, AlternativeIntent, AlternativeIntent] } {
  const row = TABLE[id];
  if (!row) return { side: 'any', alternatives: [HOLD, HOLD, HOLD] };
  const [side, codes] = row.split(':');
  const [a, b, c] = codes.split(',').map((code) => CODES[code] ?? HOLD);
  return { side: side as SituationSide, alternatives: [a, b, c] };
}

